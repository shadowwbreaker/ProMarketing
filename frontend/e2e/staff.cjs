// E2E: admin panel on demo data — dashboard, users (block/unblock), accounts moderation, orders, audit.
const { chromium } = require("playwright");
(async () => {
  const base = process.env.E2E_BASE_URL ?? "http://localhost:3000";
  const browser = await chromium.launch();
  const page = await (await browser.newContext()).newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("dialog", (d) => d.accept(d.message().includes("дней") ? "" : "E2E проверка модерации"));
  await page.goto(`${base}/login`);
  await page.getByLabel("Email").fill("demo-admin@example.com");
  await page.getByLabel("Пароль").fill("Demo-password-1");
  await page.getByRole("button", { name: "Войти" }).click();
  await page.waitForURL("**/account");
  await page.getByRole("link", { name: "Служебный раздел" }).click();
  await page.getByText("Обзор платформы").waitFor();
  await page.getByText("Комиссия платформы").waitFor();
  await page.getByRole("link", { name: "Пользователи" }).click();
  await page.getByLabel("Email или имя, Enter").fill("demo-seller2");
  await page.getByLabel("Email или имя, Enter").press("Enter");
  await page.getByRole("link", { name: "demo-seller2@example.com" }).click();
  await page.getByRole("button", { name: "Заблокировать" }).click();
  await page.getByText("Статус: blocked").waitFor();
  await page.getByRole("button", { name: "Разблокировать" }).click();
  await page.getByText("Статус: active").waitFor();
  await page.getByRole("link", { name: "Аккаунты" }).click();
  await page.getByText("Найдено:").waitFor();
  await page.getByRole("button", { name: "На проверку" }).first().click();
  await page.getByText("under_review").first().waitFor();
  await page.getByRole("button", { name: "Одобрить" }).first().click();
  await page.getByRole("link", { name: "Заказы" }).click();
  await page.getByText("Найдено:").waitFor();
  await page.getByRole("link", { name: "Журнал" }).click();
  await page.getByText("Целостность журнала: не нарушена").waitFor();
  await page.getByText("user.block").first().waitFor();
  await browser.close();
  if (errors.length) throw new Error(errors.join("; "));
  console.log("E2E STAFF OK");
})().catch((e) => { console.error(e); process.exit(1); });
